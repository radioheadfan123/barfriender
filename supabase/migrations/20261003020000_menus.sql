-- Menus: a named collection of drinks/combos. Private when it's just the owner; shared once the owner
-- makes an invite link (anyone signed in who opens it joins with the link's role). Roles: owner, editor,
-- viewer. A drink added to a menu is a COPY (combos.menu_id set); personal saves keep menu_id null.

create table menus (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 80),
  owner_id    uuid not null default auth.uid() references auth.users on delete cascade,
  created_at  timestamptz not null default now()
);

create table menu_members (
  menu_id     bigint not null references menus on delete cascade,
  user_id     uuid not null references auth.users on delete cascade,
  role        text not null check (role in ('owner', 'editor', 'viewer')),
  email       text,                         -- shown in the member list (auth.users isn't readable)
  joined_at   timestamptz not null default now(),
  primary key (menu_id, user_id)
);
create index menu_members_user_idx on menu_members (user_id);

-- One live link per menu, readable only by the owner.
create table menu_invites (
  menu_id     bigint primary key references menus on delete cascade,
  code        text not null unique default replace(gen_random_uuid()::text, '-', ''),
  role        text not null default 'editor' check (role in ('editor', 'viewer'))
);

alter table combos add column menu_id bigint references menus on delete cascade;
create index combos_menu_idx on combos (menu_id);

-- The caller's role in a menu (null = not a member). Definer, so policies can ask without recursion.
create function menu_role(m bigint) returns text
language sql stable security definer set search_path = public as $$
  select role from menu_members where menu_id = m and user_id = (select auth.uid());
$$;
revoke execute on function menu_role(bigint) from public, anon;
grant execute on function menu_role(bigint) to authenticated;

-- The owner becomes a member on creation; caps keep one account from filling the database.
create function menus_before() returns trigger language plpgsql set search_path = public as $$
begin
  if (select count(*) from menus where owner_id = new.owner_id) >= 50 then
    raise exception 'You can own up to 50 menus.' using errcode = 'check_violation';
  end if;
  return new;
end $$;
create trigger menus_cap before insert on menus for each row execute function menus_before();

create function menus_after() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into menu_members (menu_id, user_id, role, email) values (new.id, new.owner_id, 'owner', auth.jwt() ->> 'email');
  return null;
end $$;
create trigger menus_owner after insert on menus for each row execute function menus_after();

create function menu_combos_cap() returns trigger language plpgsql set search_path = public as $$
begin
  if new.menu_id is not null and (select count(*) from combos where menu_id = new.menu_id) >= 300 then
    raise exception 'A menu can hold up to 300 drinks and combos.' using errcode = 'check_violation';
  end if;
  return new;
end $$;
create trigger menu_combos_cap before insert on combos for each row execute function menu_combos_cap();

-- Join with a link. Already a member: just returns the menu.
create function join_menu(invite text) returns bigint
language plpgsql security definer set search_path = public as $$
declare inv menu_invites;
begin
  if (select auth.uid()) is null then raise exception 'Sign in first.'; end if;
  select * into inv from menu_invites where code = invite;
  if inv is null then raise exception 'This invite link is no longer valid.'; end if;
  if exists (select 1 from menu_members where menu_id = inv.menu_id and user_id = (select auth.uid())) then
    return inv.menu_id;
  end if;
  if (select count(*) from menu_members where menu_id = inv.menu_id) >= 30 then
    raise exception 'This menu is full (30 people).';
  end if;
  insert into menu_members (menu_id, user_id, role, email)
    values (inv.menu_id, (select auth.uid()), inv.role, auth.jwt() ->> 'email');
  return inv.menu_id;
end $$;
revoke execute on function join_menu(text) from public, anon;
grant execute on function join_menu(text) to authenticated;

-- RLS ------------------------------------------------------------------------------------------
alter table menus enable row level security;
alter table menu_members enable row level security;
alter table menu_invites enable row level security;

create policy "members read menus" on menus for select to authenticated using (menu_role(id) is not null);
create policy "create own menus"   on menus for insert to authenticated with check (owner_id = (select auth.uid()));
create policy "owner edits menus"  on menus for update to authenticated using (menu_role(id) = 'owner');
create policy "owner deletes menus" on menus for delete to authenticated using (menu_role(id) = 'owner');

create policy "members read members" on menu_members for select to authenticated using (menu_role(menu_id) is not null);
create policy "owner sets roles" on menu_members for update to authenticated
  using (menu_role(menu_id) = 'owner' and role <> 'owner') with check (role in ('editor', 'viewer'));
create policy "owner removes, members leave" on menu_members for delete to authenticated
  using (role <> 'owner' and (user_id = (select auth.uid()) or menu_role(menu_id) = 'owner'));

create policy "owner manages invite" on menu_invites for all to authenticated
  using (menu_role(menu_id) = 'owner') with check (menu_role(menu_id) = 'owner');

-- Combos: personal (menu_id null) stay owner-only; menu combos follow the member's role.
drop policy "own combos" on combos;
create policy "read combos" on combos for select to authenticated
  using ((menu_id is null and user_id = (select auth.uid())) or (menu_id is not null and menu_role(menu_id) is not null));
create policy "add combos" on combos for insert to authenticated
  with check (user_id = (select auth.uid()) and (menu_id is null or menu_role(menu_id) in ('owner', 'editor')));
create policy "edit combos" on combos for update to authenticated
  using ((menu_id is null and user_id = (select auth.uid())) or menu_role(menu_id) in ('owner', 'editor'))
  with check ((menu_id is null and user_id = (select auth.uid())) or menu_role(menu_id) in ('owner', 'editor'));
create policy "delete combos" on combos for delete to authenticated
  using ((menu_id is null and user_id = (select auth.uid())) or menu_role(menu_id) in ('owner', 'editor'));

drop policy "own combo items" on combo_items;
create policy "read combo items" on combo_items for select to authenticated
  using (exists (select 1 from combos c where c.id = combo_id));            -- combos RLS decides
create policy "write combo items" on combo_items for all to authenticated
  using (exists (select 1 from combos c where c.id = combo_id
    and ((c.menu_id is null and c.user_id = (select auth.uid())) or menu_role(c.menu_id) in ('owner', 'editor'))))
  with check (exists (select 1 from combos c where c.id = combo_id
    and ((c.menu_id is null and c.user_id = (select auth.uid())) or menu_role(c.menu_id) in ('owner', 'editor'))));

-- Column privileges: who made a combo and which menu it's in never change after insert (copy instead),
-- and a member row only ever changes its role.
revoke update on combos from authenticated;
grant update (name, notes, is_drink) on combos to authenticated;
revoke update on menu_members from authenticated;
grant update (role) on menu_members to authenticated;
revoke insert on menu_members from authenticated;          -- only the trigger and join_menu() add members
revoke update on menus from authenticated;
grant update (name) on menus to authenticated;
revoke all on menus, menu_members, menu_invites from anon;

-- Live updates while a menu is open. Realtime can't apply RLS to DELETE events, so only combos and menus
-- are published (a delete leaks just an id); item edits bump their combo so viewers still see them.
alter table combos add column updated_at timestamptz not null default now();
create function combo_items_touch() returns trigger language plpgsql security definer set search_path = public as $$
begin
  update combos set updated_at = now() where id = coalesce(new.combo_id, old.combo_id);
  return null;
end $$;
create trigger combo_items_touch after insert or update or delete on combo_items
  for each row execute function combo_items_touch();
alter publication supabase_realtime add table menus, combos;
