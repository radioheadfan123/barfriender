-- pourpair schema: ingredients, undirected pairings, user combos/recipes.
-- Rows with created_by / user_id null come from the book (seed data, read-only to users).

create table ingredients (
  id          bigint generated by default as identity primary key,
  name        text not null,
  key         text not null unique,          -- normalized for matching ('limes' and 'lime' -> 'lime')
  aliases     text[] not null default '{}',
  season      text,
  taste       text,
  weight      text,
  volume      text,
  is_entry    boolean not null default false, -- has its own entry in the book
  is_bar      boolean not null default false, -- tagged later
  created_by  uuid references auth.users on delete cascade,
  created_at  timestamptz not null default now()
);

create table pairings (
  id          bigint generated by default as identity primary key,
  a_id        bigint not null references ingredients on delete cascade,
  b_id        bigint not null references ingredients on delete cascade,
  strength    smallint not null default 1 check (strength between 1 and 4),
  note        text,
  created_by  uuid references auth.users on delete cascade,  -- null = book suggestion
  created_at  timestamptz not null default now(),
  check (a_id < b_id),                                        -- undirected: one row per pair
  unique nulls not distinct (a_id, b_id, created_by)
);
create index pairings_b_idx on pairings (b_id);

create table combos (
  id          bigint generated by default as identity primary key,
  user_id     uuid references auth.users on delete cascade,  -- null = book 'Flavor Affinities'
  name        text not null,
  notes       text,
  is_public   boolean not null default false,
  created_at  timestamptz not null default now()
);

create table combo_items (
  combo_id      bigint not null references combos on delete cascade,
  ingredient_id bigint not null references ingredients on delete cascade,
  amount        text,                                         -- '2 oz', 'dash'; null for plain combos
  position      smallint not null default 0,
  primary key (combo_id, ingredient_id)
);

-- RLS: everyone reads book rows + public combos; signed-in users write only their own rows.
alter table ingredients enable row level security;
alter table pairings    enable row level security;
alter table combos      enable row level security;
alter table combo_items enable row level security;

create policy "read ingredients" on ingredients for select using (true);
create policy "own ingredients"  on ingredients for all to authenticated
  using (created_by = auth.uid()) with check (created_by = auth.uid());

create policy "read pairings" on pairings for select
  using (created_by is null or created_by = auth.uid());
create policy "own pairings"  on pairings for all to authenticated
  using (created_by = auth.uid()) with check (created_by = auth.uid());

create policy "read combos" on combos for select
  using (is_public or user_id = auth.uid());
create policy "own combos"  on combos for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "read combo items" on combo_items for select
  using (exists (select 1 from combos c where c.id = combo_id and (c.is_public or c.user_id = auth.uid())));
create policy "own combo items"  on combo_items for all to authenticated
  using (exists (select 1 from combos c where c.id = combo_id and c.user_id = auth.uid()))
  with check (exists (select 1 from combos c where c.id = combo_id and c.user_id = auth.uid()));

-- Core feature: what pairs with ALL of the selected ingredients, best first.
-- Uses book pairings plus the caller's own (RLS on pairings applies; security invoker).
create function mutual_pairings(ids bigint[])
returns table (id bigint, name text, score int, weakest smallint)
language sql stable security invoker as $$
  with edges as (
    select case when a_id = any(ids) then b_id else a_id end as other,
           case when a_id = any(ids) then a_id else b_id end as picked,
           strength
    from pairings
    where a_id = any(ids) or b_id = any(ids)
  ), per_pick as (                    -- one strength per (candidate, picked), the user's or the book's
    select other, picked, max(strength) as strength
    from edges where other <> all(ids)
    group by other, picked
  )
  select i.id, i.name, sum(p.strength)::int as score, min(p.strength) as weakest
  from per_pick p join ingredients i on i.id = p.other
  group by i.id, i.name
  having count(*) = cardinality(ids)
  order by score desc, i.name;
$$;
