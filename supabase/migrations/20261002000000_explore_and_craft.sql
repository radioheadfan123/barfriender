-- Explore + Craft: bring back the book's strength, short pair notes, taste profile and classic combos,
-- tag bar ingredients, and let a saved combo be a drink.

alter table pairings
  add column strength smallint not null default 1 check (strength between 1 and 4),
  add column note text;

alter table ingredients
  add column taste text, add column season text, add column weight text, add column volume text,
  add column is_bar boolean not null default false;

-- Book 'flavor affinities' (e.g. lime + mint + rum). Rebuilt wholesale on reload, so no FKs.
create table affinities (
  id             bigint generated by default as identity primary key,
  ingredient_ids bigint[] not null
);
create index affinities_ids_idx on affinities using gin (ingredient_ids);
alter table affinities enable row level security;
create policy "read affinities" on affinities for select using (true);

alter table combos add column is_drink boolean not null default false;

-- What pairs with ALL of the picks. strength = the weakest link across the picks.
drop function mutual_pairings(bigint[]);
create function mutual_pairings(ids bigint[], bar_only boolean default false)
returns table (id bigint, name text, strength smallint)
language sql stable security invoker as $$
  select i.id, i.name, min(p.strength)::smallint
  from pairings p
  join ingredients i on i.id = case when p.a_id = any(ids) then p.b_id else p.a_id end
  where (p.a_id = any(ids) or p.b_id = any(ids)) and i.id <> all(ids) and (not bar_only or i.is_bar)
  group by i.id, i.name
  having count(distinct case when p.a_id = any(ids) then p.a_id else p.b_id end) = cardinality(ids)
  order by 3 desc, i.name;
$$;

-- Everything one ingredient pairs with, strongest first (Explore).
create function ingredient_pairings(ing bigint)
returns table (id bigint, name text, strength smallint, note text)
language sql stable security invoker as $$
  select i.id, i.name, p.strength, p.note
  from pairings p
  join ingredients i on i.id = case when p.a_id = ing then p.b_id else p.a_id end
  where ing in (p.a_id, p.b_id)
  order by p.strength desc, i.name;
$$;
