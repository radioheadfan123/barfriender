"""Turn data/flavor_bible.json into supabase/seed.sql (book rows: created_by null).

Usage: py scripts/load.py

Every pairing partner becomes an ingredient row, so multi-select works on ids.
Names are matched by a normalized key: 'limes' / 'lime' / 'MINT — IN GENERAL' / 'mint'.
Pairings are undirected: (a, b) and (b, a) collapse to one row with the higher strength.
Seed file is gitignored: it is the book's data.
"""
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BATCH = 1000


def singular(word):
    if len(word) > 3 and word.endswith("ies"):
        return word[:-3] + "y"
    if len(word) > 3 and word.endswith(("oes", "ches", "shes", "xes")):
        return word[:-2]
    if len(word) > 3 and word.endswith("s") and not word.endswith(("ss", "us", "is")):
        return word[:-1]
    return word


def key(name):
    n = name.lower().replace("’", "'")
    n = re.sub(r"\s*—\s*in general$", "", n)
    n = n.replace(" — ", ", ")
    if n.count(",") == 1:                       # 'cream, sour' / 'sour cream', 'pepper, black' / 'black pepper'
        head, tail = (s.strip() for s in n.split(","))
        n = f"{tail} {head}"
    return " ".join(singular(w) for w in re.findall(r"[\w'&-]+|[,/]", n)).replace(" ,", ",")


def build(entries):
    ids, rows = {}, []                    # key -> id, ingredient rows

    def ingredient(name, entry=None):
        k = key(name)
        if k not in ids:
            ids[k] = len(rows) + 1
            rows.append({"id": ids[k], "name": name, "key": k, "aliases": [], "entry": None})
        row = rows[ids[k] - 1]
        if entry and not row["entry"]:
            row["entry"], row["name"] = entry, re.sub(r"\s*—\s*in general$", "", name)
        return ids[k]

    # entries first so they own their keys and display names
    for e in entries:
        i = ingredient(e["name"], e)
        alias_names = e["aliases"] + [p.strip() for p in e["name"].split(" / ")[1:]]
        if " / " in e["name"]:
            alias_names.append(e["name"].split(" / ")[0])
        for a in alias_names:
            a = re.sub(r"\s*—\s*in general$", "", a)
            ids.setdefault(key(a), i)
            rows[i - 1]["aliases"].append(a)

    pairs = {}
    for e in entries:
        a = ids[key(e["name"])]
        for p in e["pairings"]:
            b = ingredient(p["name"])
            if a == b:
                continue
            k = (min(a, b), max(a, b))
            old = pairs.get(k)
            if not old or p["strength"] > old["strength"]:
                pairs[k] = {"strength": p["strength"], "note": p["note"] or (old or {}).get("note")}

    combos = []
    for e in entries:
        for items in e["affinities"]:
            item_ids = list(dict.fromkeys(ingredient(n) for n in items))
            if len(item_ids) > 1:
                combos.append((" + ".join(items), item_ids))
    return rows, pairs, combos


def q(v):
    if v is None:
        return "null"
    if isinstance(v, list):
        return "array[" + ",".join(q(x) for x in v) + "]::text[]" if v else "'{}'"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def inserts(table, cols, values):
    out = []
    for s in range(0, len(values), BATCH):
        chunk = values[s:s + BATCH]
        out.append(f"insert into {table} ({', '.join(cols)}) overriding system value values\n"
                   if "id" in cols else f"insert into {table} ({', '.join(cols)}) values\n")
        out.append(",\n".join("(" + ", ".join(q(v) for v in row) + ")" for row in chunk) + ";\n")
    return out


def main():
    entries = json.loads((ROOT / "data" / "flavor_bible.json").read_text(encoding="utf-8"))
    rows, pairs, combos = build(entries)

    ing = []
    for r in rows:
        m = (r["entry"] or {}).get("meta", {})
        ing.append([r["id"], r["name"], r["key"], sorted(set(r["aliases"])), m.get("season"),
                    m.get("taste"), m.get("weight"), m.get("volume"), r["entry"] is not None])
    pr = [[a, b, v["strength"], v["note"]] for (a, b), v in sorted(pairs.items())]
    cb = [[n + 1, name, True] for n, (name, _) in enumerate(combos)]
    ci = [[n + 1, iid, pos] for n, (_, items) in enumerate(combos) for pos, iid in enumerate(items)]

    sql = ["-- generated by scripts/load.py from The Flavor Bible. Do not commit.\nbegin;\n"]
    sql += inserts("ingredients", ["id", "name", "key", "aliases", "season", "taste", "weight", "volume",
                                   "is_entry"], ing)
    sql += inserts("pairings", ["a_id", "b_id", "strength", "note"], pr)
    sql += inserts("combos", ["id", "name", "is_public"], cb)
    sql += inserts("combo_items", ["combo_id", "ingredient_id", "position"], ci)
    sql.append("select setval(pg_get_serial_sequence('ingredients', 'id'), (select max(id) from ingredients));\n")
    sql.append("select setval(pg_get_serial_sequence('combos', 'id'), (select max(id) from combos));\n")
    sql.append("commit;\n")
    out = ROOT / "supabase" / "seed.sql"
    out.write_text("".join(sql), encoding="utf-8")

    entry_rows = sum(1 for r in rows if r["entry"])
    print(f"{len(rows)} ingredients ({entry_rows} book entries), {len(pr)} pairings, "
          f"{len(cb)} combos -> {out} ({out.stat().st_size // 1024} KB)")
    return rows, pairs


if __name__ == "__main__":
    rows, pairs = main()
    # self-check: plural/singular and 'in general' entries link up with their partners
    assert key("limes") == key("lime") and key("MINT — IN GENERAL".lower()) == key("mint")
    assert key("cherries") == key("cherry") and key("tomatoes") == key("tomato")
    assert key("cream, sour") == key("sour cream") and key("pepper, black") == key("black pepper")
    by_name = {r["key"]: r["id"] for r in rows}
    assert all(a < b for a, b in pairs)
    lime, mint = by_name[key("lime")], by_name[key("mint")]
    assert (min(lime, mint), max(lime, mint)) in pairs, "lime + mint should pair"
    print("checks ok; most-linked:", Counter(x for ab in pairs for x in ab).most_common(3))
